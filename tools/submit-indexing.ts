import fs from "fs";
import path from "path";
import { google } from "googleapis";
import { SEO_PAGES, getAllCityPageParams } from "../lib/seo-pages.js";

// Configuration
const SITE_URL = "https://technostripe.com";
const BATCH_SIZE = 200; // Google Indexing API Quota per day
const STATE_FILE = path.join(process.cwd(), "tools", "indexing-state.json");
const CREDENTIALS_FILE = path.join(process.cwd(), "service-account.json");

// Gather all URLs
const seoPageUrls = SEO_PAGES.map((page) => `${SITE_URL}/${page.slug}`);
const citySeoPageUrls = getAllCityPageParams().map((p) => `${SITE_URL}/${p.slug}/${p.service}`);
const allUrls = [...seoPageUrls, ...citySeoPageUrls];

async function submitUrls() {
  if (!fs.existsSync(CREDENTIALS_FILE)) {
    console.error("❌ Missing service-account.json in the project root.");
    console.error("Please add your Google Cloud service account key as 'service-account.json' to use the Indexing API.");
    return;
  }

  // Read state to know which URLs are already submitted
  let state = { submitted: [] };
  if (fs.existsSync(STATE_FILE)) {
    state = JSON.parse(fs.readFileSync(STATE_FILE, "utf-8"));
  }

  // Find unsubmitted URLs
  const unsubmittedUrls = allUrls.filter(url => !state.submitted.includes(url));
  console.log(`📊 Total URLs generated by script: ${allUrls.length}`);
  console.log(`✅ Already submitted: ${state.submitted.length}`);
  console.log(`⏳ Remaining to submit: ${unsubmittedUrls.length}`);

  if (unsubmittedUrls.length === 0) {
    console.log("🎉 All URLs have been submitted!");
    return;
  }

  // Get the batch of URLs for today
  const batch = unsubmittedUrls.slice(0, Math.min(BATCH_SIZE, unsubmittedUrls.length));
  console.log(`🚀 Submitting ${batch.length} URLs to Google Indexing API...`);

  // Auth with Google
  const auth = new google.auth.GoogleAuth({
    keyFile: CREDENTIALS_FILE,
    scopes: ["https://www.googleapis.com/auth/indexing"],
  });

  const authClient = await auth.getClient();
  const indexing = google.indexing({ version: "v3", auth: authClient });

  let successCount = 0;
  let failCount = 0;

  for (const url of batch) {
    try {
      await indexing.urlNotifications.publish({
        requestBody: {
          url: url,
          type: "URL_UPDATED",
        },
      });
      state.submitted.push(url);
      successCount++;
      console.log(`[SUCCESS] Submitted: ${url}`);
    } catch (error) {
      failCount++;
      console.error(`[ERROR] Failed to submit: ${url}`, error.message);
      // Brief pause to avoid rate limiting
      await new Promise(r => setTimeout(r, 500));
    }
  }

  // Save state
  fs.writeFileSync(STATE_FILE, JSON.stringify(state, null, 2));
  console.log(`\n✅ Batch complete. Success: ${successCount}, Failed: ${failCount}`);
  
  if (successCount > 0) {
    console.log(`Come back tomorrow to submit the next ${BATCH_SIZE}!`);
  }
}

submitUrls().catch(console.error);
